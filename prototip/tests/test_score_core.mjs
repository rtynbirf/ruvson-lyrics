import test from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const корень = join(dirname(fileURLToPath(import.meta.url)), '..');
globalThis.window = globalThis;
await import(join(корень, 'js', 'pitch-core.js'));
await import(join(корень, 'js', 'score-core.js'));
const ПИТЧ = globalThis.window.__ПИТЧ;
const СЧЁТ = globalThis.window.__СЧЁТ;

/* помощник: устойчивый голос на полутоне п (60% кадра), тишина дальше */
function кадрыСтроки(меткаСек, конецСек, полутон, доляГолоса = 0.6, ш = 0.05) {
  const кадры = [];
  const шаг = 0.05;
  for (let т = меткаСек; т < конецСек; т += шаг) {
    const вОкне = (т - меткаСек) / (конецСек - меткаСек);
    if (вОкне < доляГолоса) {
      кадры.push({ времяСек: т, полутон: полутон + (Math.sin(т * 997) * ш), ясность: 0.8 });
    } else {
      кадры.push({ времяСек: т, полутон: NaN, ясность: 0.1 });
    }
  }
  return кадры;
}

test('питч-ядро: полутоны от Ля считаются честно', () => {
  assert.ok(Math.abs(ПИТЧ.полутонОтЛя(440)) < 1e-9, '440 Гц = 0 полутонов от A4');
  assert.ok(Math.abs(ПИТЧ.полутонОтЛя(880) - 12) < 1e-9, '880 Гц = +12');
  assert.throws(() => ПИТЧ.полутонОтЛя(-5), RangeError);
});

test('питч-ядро: YIN находит тон чистого синуса', () => {
  const чд = 48000;
  const н = чд; /* 1 секунда */
  const х = new Float32Array(н);
  for (let i = 0; i < н; i++) х[i] = 0.4 * Math.sin(2 * Math.PI * 220 * i / чд);
  const попадание = ПИТЧ.высота(х, чд);
  assert.ok(попадание, 'синус 220 Гц не должен быть тишиной');
  assert.ok(Math.abs(попадание.герц - 220) < 4, 'герц уполз: ' + попадание.герц);
  /* тишина — честный null */
  assert.equal(ПИТЧ.высота(new Float32Array(4096), чд), null);
});

test('Дружелюбный щадит слабые попытки сильнее, чем Судья', () => {
  const кадры = кадрыСтроки(10, 14, 0, 0.45);
  const строки = [{ индекс: 0, меткаСек: 10, конецСек: 14 }];
  const оценка = СЧЁТ.попытка(кадры, строки, null);
  const друг = оценка.построчно[0].друг;
  const суд = оценка.построчно[0].суд;
  assert.ok(друг !== null && суд !== null, 'обе шкалы должны сработать');
  assert.ok(друг > суд, 'Дружелюбный (' + друг + ') должен быть мягче Судьи (' + суд + ')');
});

test('Судья штрафует девиацию от эталона', () => {
  const кадры = кадрыСтроки(10, 14, 3); /* поём на 3 полутона выше эталона */
  const строки = [{ индекс: 0, меткаСек: 10, конецСек: 14 }];
  const безЭталона = СЧЁТ.попытка(кадры, строки, null);
  const сЭталоном = СЧЁТ.попытка(кадры, строки, { '0': 0 });
  const судБез = безЭталона.построчно[0].суд;
  const судС = сЭталоном.построчно[0].суд;
  assert.ok(судС < судБез, 'судья с эталоном (' + судС + ') строже, чем без (' + судБез + ')');
});

test('Зелёный коридор: одна удача — полшага, две подряд — полутон к оригиналу', () => {
  const друг = 80, суд = 70; /* удача по канону: друг ≥ 75, суд ≥ 65 */
  /* старт −3 полутона от оригинала */
  let кор = { копилка: false, серия: 0, отвоёвано: 0 };
  let шаг = СЧЁТ.коридорШаг(кор, -3, друг, суд);
  assert.equal(шаг.удача, true);
  assert.equal(шаг.кор.копилка, true, 'первая удача кладёт полшага');
  assert.equal(шаг.новаяТранспозиция, -3, 'первая удача ещё не двигает');
  шаг = СЧЁТ.коридорШаг(шаг.кор, -3, друг, суд);
  assert.equal(шаг.новаяТранспозиция, -2, 'вторая подряд — полутон к оригиналу');
  assert.equal(шаг.кор.отвоёвано, 1, 'полутон отвоёван');
  assert.ok(шаг.событие.indexOf('сузился') !== -1);
});

test('Зелёный коридор: провал сжигает копилку', () => {
  let кор = { копилка: true, серия: 1, отвоёвано: 0 };
  const шаг = СЧЁТ.коридорШаг(кор, -2, 40, 30);
  assert.equal(шаг.удача, false);
  assert.equal(шаг.кор.копилка, false, 'копилка сгорела');
  assert.equal(шаг.новаяТранспозиция, -2, 'поле не двигалось');
  assert.ok(шаг.событие.indexOf('сгорел') !== -1);
});

test('Зелёный коридор: в оригинале — празден, но серия честна', () => {
  let кор = { копилка: true, серия: 1, отвоёвано: 0 };
  const шаг = СЧЁТ.коридорШаг(кор, 0, 90, 80);
  assert.equal(шаг.новаяТранспозиция, 0);
  assert.ok(шаг.событие.indexOf('оригинале') !== -1);
});

test('профиль лучшего дубля строится из спетых строк', () => {
  const построчно = [
    { индекс: 0, медианаПолутон: 0.2 },
    { индекс: 1, медианаПолутон: null },
    { индекс: 2, медианаПолутон: -1.4 }
  ];
  const профиль = СЧЁТ.профильИзПопытки(построчно);
  assert.equal(профиль['0'], 0.2);
  assert.equal('1' in профиль, false, 'неспетая строка не попадает в эталон');
  assert.equal(профиль['2'], -1.4);
});

  /* волна №33 — конвейер 5/5: песня из адреса ?song=nNN (умолчание n01);
     состояние (коридор, тап-метки, журнал) — у каждой песни своё */
  var идПесни = (new URLSearchParams(location.search).get('song') || 'n01');

  window.__ПЕСНЯ = window.__ПЕСНИ[идПесни];

  /* хранилище с гардом: порченый JSON не валит дом; ключи — по песне */
  var КВ = {
    взять: function (ключ, умолчание) {
      try {
        var сырой = localStorage.getItem('kv.prototip.' + идПесни + '.' + ключ);
        if (сырой === null) return умолчание;
        return JSON.parse(сырой);
      } catch (е) { return умолчание; }
    },
    положить: function (ключ, значение) {
      try { localStorage.setItem('kv.prototip.' + идПесни + '.' + ключ, JSON.stringify(значение)); }
      catch (е) { статус('Хранилище полно: ' + (е && е.message ? е.message : е)); }
    }
  };

  function минут(сек) {
    сек = Math.max(0, Math.floor(сек));
    return Math.floor(сек / 60) + ':' + ('0' + (сек % 60)).slice(-2);
  }

  /* ══════════ 2. состояние домика ══════════ */
  var кор = КВ.взять('коридор', { копилка: false, серия: 0, отвоёвано: 0 });
  var транспозиция = КВ.взять('транспозиция', 0);
  var offsetМс = КВ.взять('offset', 0);
  var тапМетки = КВ.взять('тапМетки', null);       /* {индексСтроки: времяМс} */
  var профиль = КВ.взять('профиль', null);          /* {индексСтроки: полутон} — эталон судьи */
  var журнал = КВ.взять('журнал', []);              /* попытки, последние 10 */
  var номерПопытки = журнал.length ? журнал[журнал.length - 1].н + 1 : 1;

  var строки = [];        /* [{индекс, меткаСек, конецСек, текст, label}] */
  var кадры = [];         /* [{времяСек, полутон, ясность}] текущей попытки */
  var микрофон = null;    /* MediaStream */
  var анализатор = null;
  var записыватель = null;
  var частейЗаписи = [];
  var идётПение = false;
  var активныйИндекс = -1;
  var синхроУказатель = 0; /* для тап-синхро: следующая строка к разметке */

  /* ══════════ 3. LRC: донор __ЛРЦ разбирает, секции строим из сырых label ══════════ */
  async function загрузитьЛирку() {
    var сырой = await (await fetch(window.__ПЕСНЯ.lrcFile)).text();
    var разбор = window.__ЛРЦ.разобрать(сырой);
    if (!разбор.строки.length) throw new Error('в лирке нет строк: ' + window.__ПЕСНЯ.lrcFile);

    /* секции: идём по сырому тексту, [label:X] открывает секцию */
    var секции = [];
    var текущая = null;
    сырой.split(/\r\n|\n|\r/).forEach(function (сырая) {
      var обрезанная = сырая.trim();
      var меткаLabel = обрезанная.match(/^\[label:([^\]]*)\]$/);
      if (меткаLabel) {
        текущая = { label: меткаLabel[1], индексы: [] };
        секции.push(текущая);
        return;
      }
      if (/^\[\d{1,3}:\d{1,2}/.test(обрезанная) && текущая) текущая.индексы.push(обрезанная);
    });

    /* строки в порядке файла (донор сохраняет порядок) */
    строки = [];
    var указательСекции = 0;
    разбор.строки.forEach(function (с, i) {
      /* донор отдает только текстовые строки с метками; label-строки отфильтрованы */
      while (указательСекции < секции.length &&
             секции[указательСекции].индексы.length === 0 &&
             секции[указательСекции] !== секции[0]) указательСекции++;
      var лейбл = секции[Math.min(указательСекции, секции.length - 1)].label;
      строки.push({
        индекс: i,
        меткаМс: с.времяМс,
        текст: с.текст || '',
        label: лейбл
      });
    });
    /* label-строки и песенные строки чередуются 1:1 по порядку файла —
       пересобираем честно: пересчёт лейбла по позиции в сыром списке */
    var строкаЛейбл = null;
    var к = 0;
    сырой.split(/\r\n|\n|\r/).forEach(function (сырая) {
      var обрезанная = сырая.trim();
      var меткаLabel = обрезанная.match(/^\[label:([^\]]*)\]$/);
      if (меткаLabel) { строкаЛейбл = меткаLabel[1]; return; }
      if (/^\[\d{1,3}:\d{1,2}/.test(обрезанная)) {
        if (строки[к]) строки[к].label = строкаЛейбл;
        к++;
      }
    });

    строки.forEach(function (с, i) {
      с.меткаМс = (тапМетки && тапМетки[String(с.индекс)] != null) ? тапМетки[String(с.индекс)] : с.меткаМс;
      с.меткаСек = с.меткаМс / 1000;
      с.конецСек = (i + 1 < строки.length ? строки[i + 1].меткаМс : window.__ПЕСНЯ.durSec * 1000) / 1000;
    });
    разборСекцийДляЛент = секции;
    return разбор;
  }
  var разборСекцийДляЛент = null;

  /* ══════════ 4. сцена: DOM без единого innerHTML ══════════ */
  function строитьСцену() {
    var контейнер = $('сцена-строки');
    while (контейнер.firstChild) контейнер.removeChild(контейнер.firstChild);

    [предСтрока, текущСтрока, следСтрока].forEach(function (роль, i) {
      var обёртка = document.createElement('div');
      обёртка.className = 'строка ' + ['строка-прошлая', 'строка-текущая', 'строка-след'][i];
      var лейбл = document.createElement('div');
      лейбл.className = 'строка-лейбл';
      var текст = document.createElement('div');
      текст.className = 'строка-текст';
      обёртка.appendChild(лейбл);
      обёртка.appendChild(текст);
      контейнер.appendChild(обёртка);
      роль.узел = обёртка;
      роль.текст = текст;
      роль.лейбл = лейбл;
    });
  }
  var предСтрока = {}, текущСтрока = {}, следСтрока = {};

  function подсветить(индекс) {
    if (индекс === активныйИндекс) return;
    активныйИндекс = индекс;
    var прошлое = индекс - 1, текущее = индекс, следующее = индекс + 1;
    заполнить(предСтрока, прошлое >= 0 ? строки[прошлое] : null);
    заполнить(текущСтрока, строки[текущее]);
    заполнить(следСтрока, следующее < строки.length ? строки[следующее] : null);
    var живой = $('живая-строка');
    if (живой) живой.textContent = строки[текущее] ? строки[текущее].текст : '';
  }
  function заполнить(роль, строка) {
    if (!роль.текст) return;
    роль.текст.textContent = строка ? строка.текст : '';
    роль.лейбл.textContent = строка ? строка.label : '';
    роль.узел.classList.toggle('пусто', !строка);
  }

  /* ══════════ 5. трубки: canvas с кривой тона ══════════ */
  var канвас = null, контекст2д = null;
  function трубкиГотов() {
    канвас = $('трубки');
    контекст2д = канвас.getContext('2d');
    подгонКанваса();
    window.addEventListener('resize', подгонКанваса);
  }
  function подгонКанваса() {
    var ящик = канвас.parentElement.getBoundingClientRect();
    канвас.width = Math.max(320, ящик.width) * (window.devicePixelRatio || 1);
    канвас.height = 180 * (window.devicePixelRatio || 1);
  }

  function трубкиРисовать(времяСек) {
    var ш = канвас.width, в = канвас.height;
    var dpr = window.devicePixelRatio || 1;
    контекст2д.clearRect(0, 0, ш, в);

    /* окно: последние 8 секунд */
    var окно = 8;
    var отСек = Math.max(0, времяСек - окно), доСек = времяСек + 0.5;

    /* диапазон полутонов: по кадрам окна + эталон текущей строки */
    var мин = Infinity, макс = -Infinity;
    for (var i = 0; i < кадры.length; i++) {
      var к = кадры[i];
      if (к.времяСек < отСек) continue;
      if (к.полутон < мин) мин = к.полутон;
      if (к.полутон > макс) макс = к.полутон;
    }
    if (профиль && активныйИндекс >= 0 && профиль[String(активныйИндекс)] != null) {
      var эт = профиль[String(активныйИндекс)];
      мин = Math.min(мин, эт); макс = Math.max(макс, эт);
    }
    if (!isFinite(мин) || !isFinite(макс)) { мин = -3; макс = 3; }
    мин -= 2; макс += 2;

    var полутонВY = function (п) { return в - (п - мин) / (макс - мин) * (в - 20 * dpr) - 10 * dpr; };
    var секВX = function (с) { return (с - отСек) / (доСек - отСек) * ш; };

    /* сетка полутонов */
    контекст2д.strokeStyle = 'rgba(212,175,55,0.12)';
    контекст2д.lineWidth = 1;
    for (var п = Math.ceil(мин); п <= Math.floor(макс); п++) {
      var y = полутонВY(п);
      контекст2д.beginPath();
      контекст2д.moveTo(0, y);
      контекст2д.lineTo(ш, y);
      контекст2д.stroke();
    }

    /* эталонная медиана текущей строки — золотой пунктир */
    if (профиль && активныйИндекс >= 0 && профиль[String(активныйИндекс)] != null) {
      var этY = полутонВY(профиль[String(активныйИндекс)]);
      контекст2д.strokeStyle = 'rgba(212,175,55,0.75)';
      контекст2д.setLineDash([6 * dpr, 6 * dpr]);
      контекст2д.beginPath();
      контекст2д.moveTo(0, этY);
      контекст2д.lineTo(ш, этY);
      контекст2д.stroke();
      контекст2д.setLineDash([]);
    }

    /* зелёный коридор: полоса допустимого сдвига к оригиналу */
    if (транспозиция !== 0) {
      var цветКор = 'rgba(52,211,153,0.10)';
      контекст2д.fillStyle = цветКор;
      var полВерх = полутонВY(транспозиция + 0.5), полНиз = полутонВY(транспозиция - 0.5);
      контекст2д.fillRect(0, Math.min(полВерх, полНиз), ш, Math.abs(полНиз - полВерх));
    }

    /* кривая тона певца */
    контекст2д.strokeStyle = '#34D399';
    контекст2д.lineWidth = 2.5 * dpr;
    контекст2д.lineJoin = 'round';
    контекст2д.beginPath();
    var перо = false;
    for (var j = 0; j < кадры.length; j++) {
      var кф = кадры[j];
      if (кф.времяСек < отСек) continue;
      var x = секВX(кф.времяСек), y = полутонВY(кф.полутон);
      if (!перо) { контекст2д.moveTo(x, y); перо = true; }
      else контекст2д.lineTo(x, y);
    }
    контекст2д.stroke();
  }

  /* ══════════ 6. микрофон: кадры тона ══════════ */
  async function микрофонПустить() {
    if (микрофон) return;
    if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) {
      throw new Error('микрофон недоступен: браузер не отдаёт getUserMedia (нужен https или localhost)');
    }
    микрофон = await navigator.mediaDevices.getUserMedia({
      audio: { echoCancellation: false, noiseSuppression: false, autoGainControl: false }
    });
    /* анализатор живёт в собственном тихом AudioContext (микрофонный ящик) */
    var ак = новыйАнализКонтекст();
    var источник = ак.createMediaStreamSource(микрофон);
    анализатор = ак.createAnalyser();
    анализатор.fftSize = 2048;
    источник.connect(анализатор);
    записывательГотов();
  }
  var аудиоКонтекстАнализ = null;
  function новыйАнализКонтекст() {
    var Класс = window.AudioContext || window.webkitAudioContext;
    аудиоКонтекстАнализ = new Класс();
    return аудиоКонтекстАнализ;
  }
  function записывательГотов() {
    if (!window.MediaRecorder) return false;
    if (!MediaRecorder.isTypeSupported || !MediaRecorder.isTypeSupported('audio/webm')) return false;
    записыватель = new MediaRecorder(микрофон, { mimeType: 'audio/webm' });
    частейЗаписи = [];
    записыватель.ondataavailable = function (е) { if (е.data && е.data.size) частейЗаписи.push(е.data); };
    return true;
  }

  var буферАнализа = null;
  function кадрВзять(времяСек) {
    if (!анализатор) return;
    if (!буферАнализа || буферАнализа.length !== анализатор.fftSize) {
      буферАнализа = new Float32Array(анализатор.fftSize);
    }
    анализатор.getFloatTimeDomainData(буферАнализа);
    var попадание = window.__ПИТЧ.высота(буферАнализа, аудиоКонтекстАнализ.sampleRate);
    if (попадание) {
      кадры.push({
        времяСек: времяСек,
        полутон: window.__ПИТЧ.полутонОтЛя(попадание.герц),
        ясность: попадание.ясность
      });
    }
  }

  /* ══════════ 7. главный цикл ══════════ */
  function цикл() {
    if (!идётПение) return;
    var времяСек = window.__СЦЕНА.времяСек() + offsetМс / 1000;
    кадрВзять(времяСек);
    var индекс = строкаПо(времяСек);
    подсветить(индекс);
    трубкиРисовать(времяСек);
    полосаПрогресса(времяСек);
    requestAnimationFrame(цикл);
  }

  function строкаПо(времяСек) {
    var индекс = 0;
    for (var i = 0; i < строки.length; i++) {
      if (времяСек >= строки[i].меткаСек - 0.15) индекс = i;
      else break;
    }
    return индекс;
  }

  function полосаПрогресса(времяСек) {
    var полоса = $('прогресс');
    if (!полоса) return;
    var всего = window.__ПЕСНЯ.durSec;
    полоса.value = Math.min(100, времяСек / всего * 100);
  }

  /* ══════════ 8. попытка: петь / стоп / счёт / коридор ══════════ */
  async function петь() {
    try {
      if (идётПение) return;
      статус('Просим микрофон…');
      await микрофонПустить();
      кадры = [];
      активныйИндекс = -1;
      идётПение = true;
      if (записыватель) { частейЗаписи = []; записыватель.start(); }
      window.__СЦЕНА.снулю();
      await window.__СЦЕНА.пустить(0);
      $('кнопка-петь').disabled = true;
      $('кнопка-стоп').disabled = false;
      статус('Поёшь — поле слушает. Кривая тона зелёная, эталон строки — золото.');
      requestAnimationFrame(цикл);
    } catch (е) {
      идётПение = false;
      статус('Не вышло пустить: ' + (е && е.message ? е.message : е));
    }
  }

  async function стоп() {
    if (!идётПение) return;
    идётПение = false;
    window.__СЦЕНА.пауза();
    if (записыватель && записыватель.state === 'recording') {
      await new Promise(function (резолв) {
        записыватель.onstop = резолв;
        записыватель.stop();
      });
    }
    $('кнопка-петь').disabled = false;
    $('кнопка-стоп').disabled = true;
    статус('Считаем попытку…');

    /* кадры для оценки: без offset (сцена считает в исходной шкале) */
    var сСтроки = строки.map(function (с) {
      return { индекс: с.индекс, меткаСек: с.меткаСек, конецСек: с.конецСек };
    });
    var оценка = window.__СЧЁТ.попытка(кадры, сСтроки, профиль);

    /* коридор: канон ТЗ */
    var шаг = window.__СЧЁТ.коридорШаг(кор, транспозиция, оценка.итогДруг, оценка.итогСуд);
    кор = шаг.кор;
    КВ.положить('коридор', кор);

    /* журнал попытки */
    var запись = {
      н: номерПопытки,
      друг: оценка.итогДруг,
      суд: оценка.итогСуд,
      транспозиция: транспозиция,
      отвоёвано: кор.отвоёвано,
      дата: new Date().toISOString().slice(0, 16).replace('T', ' ')
    };
    журнал.push(запись);
    if (журнал.length > 10) журнал = журнал.slice(-10);
    КВ.положить('журнал', журнал);
    номерПопытки += 1;

    /* профиль: попытка стала лучшим дублем? (по Дружелюбному) */
    var лучшийБыл = КВ.взять('лучшийДруг', null);
    if (оценка.итогДруг !== null && (лучшийБыл === null || оценка.итогДруг > лучшийБыл)) {
      профиль = window.__СЧЁТ.профильИзПопытки(оценка.построчно);
      КВ.положить('профиль', профиль);
      КВ.положить('лучшийДруг', оценка.итогДруг);
      КВ.положить('лучшийДубльН', запись.н);
    }

    /* дубликат записи в OPFS */
    var идДубля = null;
    if (частейЗаписи.length) {
      var блоб = new Blob(частейЗаписи, { type: 'audio/webm' });
      идДубля = window.__ПЕСНЯ.id + '-take-' + запись.н + '.webm';
      var буферДубля = await блоб.arrayBuffer();
      var положено = await window.__ОПФС.положить(идДубля, буферДубля);
      if (!положено || положено.ок === false) идДубля = null;
    }

    /* движение коридора — пересборка сцены */
    if (шаг.шагПолутон) {
      транспозиция = шаг.новаяТранспозиция;
      КВ.положить('транспозиция', транспозиция);
      статус('Коридор сузился: пересобираем поле под ' + транспозиция + ' полутонов…');
      await window.__СЦЕНА.собрать(транспозиция, статус);
    }

    отчётПопытки(оценка, шаг, запись, идДубля);
    вывестиПульт();
    вывестиПрофиль();
    вывестиДубли();
  }

  function отчётПопытки(оценка, шаг, запись, идДубля) {
    var ящик = $('счёт-тело');
    while (ящик.firstChild) ящик.removeChild(ящик.firstChild);

    var верх = document.createElement('div');
    верх.className = 'счёт-итоги';
    [['Дружелюбный', оценка.итогДруг, 'друг'], ['Судья', оценка.итогСуд, 'суд']].forEach(function (п) {
      var метка = document.createElement('span');
      метка.className = 'счёт-метка ' + п[2];
      метка.textContent = п[0] + ': ';
      var жир = document.createElement('b');
      жир.textContent = п[1] === null ? '—' : Math.round(п[1]);
      метка.appendChild(жир);
      верх.appendChild(метка);
    });
    ящик.appendChild(верх);

    var вердикт = document.createElement('div');
    вердикт.className = 'счёт-вердикт';
    вердикт.textContent = (шаг.событие || 'Попытка засчитана') +
      (идДубля ? ' · дубль №' + запись.н + ' сохранён' : ' · записи не было (браузер не отдал MediaRecorder)');
    ящик.appendChild(вердикт);

    /* что тренировать: три худшие спетые строки */
    var спетые = оценка.построчно.filter(function (с) { return с.друг !== null; })
      .sort(function (а, б) { return а.друг - б.друг; }).slice(0, 3);
    if (спетые.length) {
      var голова = document.createElement('div');
      голова.className = 'тренировать-голова';
      голова.textContent = 'Что тренировать:';
      ящик.appendChild(голова);
      спетые.forEach(function (с) {
        var строк = document.createElement('div');
        строк.className = 'тренировать-строка';
        строк.textContent = '· «' + (строки[с.индекс] ? строки[с.индекс].текст.slice(0, 44) : '') + '…» — ' +
          Math.round(с.друг) + (с.девиацияПолутон !== null ? ' (сдвиг ' + с.девиацияПолутон + ' пт от эталона)' : '');
        ящик.appendChild(строк);
      });
    }
  }

  /* ══════════ 9. пульт / коридор / профиль / дубли ══════════ */

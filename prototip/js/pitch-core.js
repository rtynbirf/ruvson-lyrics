/* ═══════════════════════════════════════════════════════════════════════════
   КАРАОКЕ МЕЧТЫ 2.0 · прототип СЦЕНА · js/pitch-core.js
   питч-ядро/0.1 · YIN (de Cheveigné & Kawahara 2002)

   Ящик в духе канона дома СИНГУЛЯР (доноры Витка 1):
   • 0 сети, 0 случайности, 0 часов — время и частота дискретизации приходят аргументом;
   • вход не мутируется;
   • честные русские отказы — RangeError/TypeError с русскими сообщениями;
   • детерминизм — одинаковый вход даёт одинаковый выход;
   • DOM не трогает — никакого innerHTML; только window.__ПИТЧ.
   ═══════════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';
  if (typeof window === 'undefined') {
    throw new Error('питч-ядро: ядро живёт в браузере — window не найден');
  }
  if (window.__ПИТЧ) return; /* повторная вставка — молча, один канон */

  var ИМЯ = 'питч-ядро/0.1';

  var УМОЛЧАНИЯ = Object.freeze({
    окноСэмплов: 1024,      /* окно анализа YIN */
    герцМин: 70,            /* нижняя граница голоса */
    герцМакс: 1100,         /* верхняя граница голоса */
    порогЯсности: 0.55,     /* ниже — «тишина/шум», честный null */
    порогCMND: 0.12         /* абсолютный порог YIN */
  });

  function число(х) {
    return (typeof х === 'number' && isFinite(х)) ? х : null;
  }

  function проверитьВход(x) {
    if (!(x instanceof Float32Array)) {
      throw new TypeError('вход должен быть Float32Array, пришло ' + (x === null ? 'null' : typeof x));
    }
    if (x.length === 0) return 'вход пуст: мерить нечего';
    return null;
  }

  /* ── разностная функция d(τ) ────────────────────────────────────────────── */
  function разность(x, W, тауМакс) {
    var d = new Float32Array(тауМакс + 1);
    for (var тау = 1; тау <= тауМакс; тау++) {
      var сумма = 0;
      for (var i = 0; i < W; i++) {
        var разница = x[i] - x[i + тау];
        сумма += разница * разница;
      }
      d[тау] = сумма;
    }
    return d;
  }

  /* ── кумулятивная нормированная разностная функция (CMND) ──────────────── */
  function нормализовать(d) {
    var см = new Float32Array(d.length);
    см[0] = 1;
    var бегущая = 0;
    for (var тау = 1; тау < d.length; тау++) {
      бегущая += d[тау];
      см[тау] = бегущая === 0 ? 1 : d[тау] * тау / бегущая;
    }
    return см;
  }

  /* ── параболическая интерполяция минимума ──────────────────────────────── */
  function парабола(см, тау) {
    if (тау <= 0 || тау >= см.length - 1) return тау;
    var слева = см[тау - 1], центр = см[тау], справа = см[тау + 1];
    var знаменатель = 2 * (2 * центр - слева - справа);
    if (знаменатель === 0) return тау;
    return тау + (справа - слева) / знаменатель;
  }

  /* ── главный ход: высота(сэмплы, частотаДискретизации, опции) ─────────────
     возвращает { герц, ясность } или null (тишина/шум — честный отказ).     */
  function высота(x, частотаДискретизации, опции) {
    var брак = проверитьВход(x);
    if (брак) throw new RangeError('высота: ' + брак);
    var чд = число(частотаДискретизации);
    if (чд === null || чд < 8000) {
      throw new RangeError('частотаДискретизации должна быть конечным числом ≥ 8000, пришло ' + String(частотаДискретизации));
    }
    var о = опции || {};
    var W = о.окноСэмплов !== undefined ? о.окноСэмплов : УМОЛЧАНИЯ.окноСэмплов;
    if (W < 256 || W > 8192) {
      throw new RangeError('окноСэмплов ' + W + ' вне честного диапазона 256–8192');
    }
    if (x.length < W * 2) return null; /* окна не хватает — тихо и честно */

    var герцМин = о.герцМин !== undefined ? о.герцМин : УМОЛЧАНИЯ.герцМин;
    var герцМакс = о.герцМакс !== undefined ? о.герцМакс : УМОЛЧАНИЯ.герцМакс;
    var порогЯс = о.порогЯсности !== undefined ? о.порогЯсности : УМОЛЧАНИЯ.порогЯсности;
    var порогС = о.порогCMND !== undefined ? о.порогCMND : УМОЛЧАНИЯ.порогCMND;

    /* энергия окна: если тихо — сразу null (не тратим такты) */
    var энергия = 0;
    for (var i = 0; i < W; i++) энергия += x[i] * x[i];
    var среднеквадрат = Math.sqrt(энергия / W);
    if (среднеквадрат < 0.004) return null;

    var тауМин = Math.max(2, Math.floor(чд / герцМакс));
    var тауМакс = Math.min(W - 1, Math.ceil(чд / герцМин));
    if (тауМакс <= тауМин) return null;

    var d = разность(x, W, тауМакс);
    var см = нормализовать(d);

    /* первый локальный минимум ниже порога — канон YIN */
    var найдено = -1;
    for (var т = тауМин; т <= тауМакс; т++) {
      if (см[т] < порогС) {
        while (т + 1 <= тауМакс && см[т + 1] < см[т]) т++;
        найдено = т;
        break;
      }
    }
    if (найдено === -1) {
      /* глобальный минимум как запасной ход */
      var минимум = Infinity;
      for (var т2 = тауМин; т2 <= тауМакс; т2++) {
        if (см[т2] < минимум) { минимум = см[т2]; найдено = т2; }
      }
      if (минимум > 0.55) return null; /* ярко выраженного тона нет */
    }

    var точныйТау = парабола(см, найдено);
    if (точныйТау <= 0) return null;
    var герц = чд / точныйТау;
    if (герц < герцМин || герц > герцМакс) return null;

    var ясность = Math.max(0, Math.min(1, 1 - см[найдено]));
    if (ясность < порогЯс) return null;
    return { герц: герц, ясность: ясность };
  }

  /* ── полутоны от A4 (440 Гц) и октавное сворачивание (канон ТЗ) ────────── */
  function полутонОтЛя(герц) {
    var ч = число(герц);
    if (ч === null || ч <= 0) {
      throw new RangeError('полутонОтЛя: герц должно быть положительным конечным числом');
    }
    return 12 * Math.log2(герц / 440);
  }

  function медиана(массив) {
    if (!Array.isArray(массив) || массив.length === 0) return null;
    var отсорт = массив.slice().sort(function (а, б) { return а - б; });
    var середина = Math.floor(отсорт.length / 2);
    return отсорт.length % 2 ? отсорт[середина] : (отсорт[середина - 1] + отсорт[середина]) / 2;
  }

  function инфо() {
    return {
      имя: ИМЯ,
      метод: 'YIN: разностная функция + CMND + параболическая интерполяция',
      умеет: ['моно Float32Array', 'герц 70–1100', 'ясность 0–1', 'полутоны от A4', 'медиана'],
      не_умеет: ['полифонию', ' percussion', 'WASM (честный хвост)'],
      границы: УМОЛЧАНИЯ,
      честность: '0 сети, 0 случайности, 0 часов, вход не мутируется, отказы по-русски'
    };
  }

  window.__ПИТЧ = {
    имя: ИМЯ,
    высота: высота,
    полутонОтЛя: полутонОтЛя,
    медиана: медиана,
    инфо: инфо
  };
})();

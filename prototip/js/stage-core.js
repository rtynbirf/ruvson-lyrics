/* ═══════════════════════════════════════════════════════════════════════════
   КАРАОКЕ МЕЧТЫ 2.0 · прототип СЦЕНА · js/stage-core.js
   сцена-ядро/0.1 — ящик звука: минус, шифтер, время.

   Шифтер транспонирования (канон ТЗ «±12 с сохранением темпа»):
   playbackRate = 2^(n/12) двигает тон, но и темп; донор __ВСОЛА
   (WSOLA, singulyar Виток 1) тянет сэмплы обратно с коэффициентом
   1/playbackRate — длительность восстанавливается, темп стоит.

   Законы ящика (канон дома):
   • 0 сети — минус уже в репе, fetch только на свой origin;
   • вход не мутируется; честные русские отказы;
   • мост: наружу через window.__СЦЕНА (delete + defineProperty).
   ═══════════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';
  if (typeof window === 'undefined') {
    throw new Error('сцена-ядро: ядро живёт в браузере — window не найден');
  }

  var ИМЯ = 'сцена-ядро/0.1';
  var состояние = {
    контекст: null,          /* AudioContext */
    моно: null,              /* Float32Array — моно-минус (исходник) */
    частота: 0,              /* sampleRate контекста */
    длительностьСек: 0,      /* длительность исходника, сек */
    буферИграет: null,       /* AudioBuffer текущей сборки */
    источник: null,          /* AudioBufferSourceNode */
    громкость: null,         /* GainNode */
    стартВремяКонтекста: 0,  /* ctx.currentTime на старте */
    смещениеПаузы: 0,        /* сколько секунды контента пройдено до паузы */
    играет: false,
    транспозиция: 0,         /* полутона текущей сборки */
    коэффициентВсола: 1,     /* применённый коэффициент (1 = без WSOLA) */
    строит: false
  };

  function честный(e) { return (e && e.message) ? String(e.message) : String(e); }

  /* ── мост: стираем старую копию, закрепляем новую как неизменяемую ─────── */
  function мост(имя, значение) {
    try { delete window[имя]; } catch (е) { /* строгий режим молчит дальше */ }
    Object.defineProperty(window, имя, { value: значение, writable: false, configurable: false });
  }

  /* ── подготовка: контекст + декод минуса + моно-сведение ───────────────── */
  async function загрузить(urlФайла) {
    if (состояние.контекст) return отчёт();
    var КлассКонтекста = window.AudioContext || window.webkitAudioContext;
    if (!КлассКонтекста) {
      throw new Error('Web Audio недоступен в этом браузере — поём без звука нельзя, честно');
    }
    var контекст = new КлассКонтекста();
    состояние.контекст = контекст;
    состояние.частота = контекст.sampleRate;

    var ответ = await fetch(urlФайла);
    if (!ответ.ok) {
      throw new Error('минус не скачался: ' + urlФайла + ' — статус ' + ответ.status);
    }
    var данные = await ответ.arrayBuffer();
    var буфер = await контекст.decodeAudioData(данные);
    /* моно-сведение: прототип честно поёт в моно (экономит память шифтера) */
    var слева = буфер.getChannelData(0);
    var справа = буфер.numberOfChannels > 1 ? буфер.getChannelData(1) : слева;
    var моно = new Float32Array(буфер.length);
    for (var i = 0; i < буфер.length; i++) {
      моно[i] = 0.5 * (слева[i] + справа[i]);
    }
    состояние.моно = моно;
    состояние.длительностьСек = буфер.duration;
    return отчёт();
  }

  function отчёт() {
    return {
      имя: ИМЯ,
      готов: !!состояние.моно,
      частота: состояние.частота,
      длительностьСек: Math.round(состояние.длительностьСек * 10) / 10,
      транспозиция: состояние.транспозиция,
      играет: состояние.играет
    };
  }

  /* ── шифтер: сборка буфера под n полутонов (WSOLA-компенсация темпа) ────── */
  async function собрать(n, вестиЖурнал) {
    if (!состояние.моно) throw new Error('сцена пуста: сначала загрузить минус');
    if (!Number.isInteger(n) || n < -12 || n > 12) {
      throw new RangeError('транспозиция должна быть целым числом полутонов −12…+12, пришло ' + String(n));
    }
    if (состояние.строит) throw new Error('поле уже строится: подожди, ящик не умеет параллелить');
    состояние.строит = true;
    try {
      var скорость = Math.pow(2, n / 12);
      var коэффициент = 1 / скорость; /* WSOLA: тон стоит, длительность восстанавливается */
      var сэмплы = состояние.моно;
      var буфер;
      if (n === 0) {
        буфер = буферИзМоно(сэмплы);
      } else {
        if (вестиЖурнал) вестиЖурнал('Поле строится: WSOLA тянет ' + Math.round(сэмплы.length / 1000) + 'k сэмплов…');
        /* рендер в следующий кадр, чтобы статус успел показаться */
        await новыйКадр();
        var растянуто = window.__ВСОЛА.растянуть(сэмплы, {
          коэффициент: коэффициент,
          частотаСэмплов: состояние.частота
        });
        if (растянуто && растянуто.каналы) растянуто = растянуто.каналы[0]; /* страховка формы ответа */
        буфер = буферИзМоно(растянуто);
      }
      состояние.буферИграет = буфер;
      состояние.транспозиция = n;
      состояние.коэффициентВсола = коэффициент;
      состояние.смещениеПаузы = 0;
      return отчёт();
    } finally {
      состояние.строит = false;
    }
  }

  function буферИзМоно(сэмплы) {
    var буфер = состояние.контекст.createBuffer(1, сэмплы.length, состояние.частота);
    буфер.copyToChannel(сэмплы, 0);
    return буфер;
  }

  function новыйКадр() {
    return new Promise(function (резолв) {
      if (typeof requestAnimationFrame === 'function') requestAnimationFrame(function () { резолв(); });
      else setTimeout(резолв, 30);
    });
  }

  /* ── транспорт ──────────────────────────────────────────────────────────── */
  async function пустить(секС) {
    if (!состояние.буферИграет) throw new Error('сборки нет: сначала собрать(полутона)');
    if (состояние.контекст.state === 'suspended') {
      await состояние.контекст.resume();
    }
    остановить();
    var источник = состояние.контекст.createBufferSource();
    источник.buffer = состояние.буферИграет;
    источник.playbackRate.value = Math.pow(2, состояние.транспозиция / 12);
    var громкость = состояние.контекст.createGain();
    громкость.gain.value = 1;
    источник.connect(громкость).connect(состояние.контекст.destination);
    /* старт-позиция учитывает WSOLA-растяжение: сэмплы буфера длиннее в 1/коэффициент раз */
    var смещениеБуфера = (состояние.смещениеПаузы || 0) * состояние.частота / состояние.коэффициентВсола;
    источник.start(0, Math.min(смещениеБуфера, источник.buffer.duration - 0.01));
    состояние.источник = источник;
    состояние.громкость = громкость;
    состояние.стартВремяКонтекста = состояние.контекст.currentTime;
    состояние.играет = true;
    источник.onended = function () {
      if (состояние.источник === источник) {
        состояние.играет = false;
        состояние.смещениеПаузы = 0;
        состояние.источник = null;
      }
    };
    return отчёт();
  }

  function пауза() {
    if (!состояние.играет) return отчёт();
    состояние.смещениеПаузы = времяСек();
    остановить();
    return отчёт();
  }

  function остановить() {
    if (состояние.источник) {
      try { состояние.источник.onended = null; состояние.источник.stop(); } catch (е) { /* уже тихо */ }
      состояние.источник = null;
    }
    состояние.играет = false;
  }

  function снулю() {
    остановить();
    состояние.смещениеПаузы = 0;
  }

  /* ── время песни в ИСХОДНОЙ шкале (для LRC) ───────────────────────────────
     С WSOLA-компенсацией длительность буфера = длительности исходника:
     прошедшее время и есть время песни. Без компенсации (n = 0) — тоже.    */
  function времяСек() {
    if (!состояние.контекст) return 0;
    if (!состояние.играет) return состояние.смещениеПаузы || 0;
    return (состояние.смещениеПаузы || 0) + (состояние.контекст.currentTime - состояние.стартВремяКонтекста);
  }

  function громкостьПоставить(доля) {
    if (состояние.громкость) состояние.громкость.gain.value = Math.max(0, Math.min(1, доля));
  }

  мост('__СЦЕНА', {
    имя: ИМЯ,
    загрузить: загрузить,
    собрать: собрать,
    пустить: пустить,
    пауза: пауза,
    снулю: снулю,
    времяСек: времяСек,
    громкостьПоставить: громкостьПоставить,
    состояние: функцияСостояния,
    инфо: инфо
  });

  function функцияСостояния() { return отчёт(); }
  function инфо() {
    return {
      имя: ИМЯ,
      шифтер: 'playbackRate 2^(n/12) + WSOLA 1/коэффициент = тон двигается, темп стоит',
      честность: 'моно-сведение, сборка только на явный вызов, отказы по-русски',
      всола: window.__ВСОЛА ? window.__ВСОЛА.имя : 'донор не загружен'
    };
  }
})();

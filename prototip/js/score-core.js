/* ═══════════════════════════════════════════════════════════════════════════
   КАРАОКЕ МЕЧТЫ 2.0 · прототип СЦЕНА · js/score-core.js
   счёт-ядро/0.1 — ящик оценки: Дружелюбный/Судья, Зелёный коридор.

   Канон ТЗ (docs/KARAOKE_ТЗ.md):
   • «Дружелюбный» — щадящая вогнутая кривая (sqrt-смягчение), слабые
     попытки тянутся вверх: человек поёт, а не сдаёт экзамен;
   • «Судья» — сырые числа, строгий порог ясности, штраф за девиацию
     от эталонной медианы строки (эталон = профиль лучшего дубля);
   • «Зелёный коридор»: удача (друг ≥ 75 и суд ≥ 65) кладёт полшага
     в копилку; вторая удачная подряд сужает коридор на полутон
     К ОРИГИНАЛУ (0); провал сжигает копилку. Пройденные полутоны
     копятся за всё время (corridorSteps) — пройденное не отбирают.

   Законы ящика: 0 сети, 0 DOM, 0 случайности, 0 часов (время —
   аргументом), вход не мутируется, честные русские отказы.
   ═══════════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';
  if (typeof window === 'undefined') {
    throw new Error('счёт-ядро: ядро живёт в браузере — window не найден');
  }
  if (window.__СЧЁТ) return; /* повторная вставка — молча, один канон */

  var ИМЯ = 'счёт-ядро/0.1';

  var ПОРОГ = Object.freeze({
    ясностьДруг: 0.55,      /* порог голосового кадра для Дружелюбного */
    ясностьСуд: 0.70,       /* строгий порог для Судьи */
    удачаДруг: 75,          /* канон ТЗ: две подряд (друг ≥ 75, суд ≥ 65) */
    удачаСуд: 65,
    штрафПолутон: 14,       /* баллов штрафа за полутон девиации у Судьи */
    штрафМакс: 40
  });

  /* ── кадры: [{времяСек, полутон, ясность}] → метрики строки ─────────────── */
  /* строка: { меткаСек, конецСек } — окно анализа [метка−0.15, конец−0.05]   */
  function строкаМетрики(кадры, строка, опции) {
    if (!Array.isArray(кадры)) {
      throw new TypeError('кадры должны быть массивом {времяСек, полутон, ясность}');
    }
    if (!строка || !isFinite(строка.меткаСек) || !isFinite(строка.конецСек)) {
      throw new TypeError('строка должна быть {меткаСек, конецСек} с конечными числами');
    }
    var о = опции || {};
    var порогЯс = о.порогЯсности !== undefined ? о.порогЯсности : ПОРОГ.ясностьДруг;
    var окноНач = строка.меткаСек - 0.15;
    var окноКон = Math.max(окноНач + 0.2, строка.конецСек - 0.05);

    var вОкне = 0, активные = [];
    for (var i = 0; i < кадры.length; i++) {
      var к = кадры[i];
      if (к.времяСек < окноНач || к.времяСек >= окноКон) continue;
      вОкне++;
      if (к.ясность >= порогЯс && isFinite(к.полутон)) активные.push(к);
    }
    if (вОкне === 0) {
      return { покрытие: 0, устойчивость: 0, старт: 0, медианаПолутон: null, активных: 0 };
    }
    var покрытие = активные.length / вОкне;
    /* покрытие-складка: паузы в тексте не караем — покрытие ≥ 0.35 считается полным */
    покрытие = Math.min(1, покрытие / 0.35);

    if (активные.length === 0) {
      return { покрытие: 0, устойчивость: 0, старт: 0, медианаПолутон: null, активных: 0 };
    }

    var полутоны = активные.map(function (к) { return к.полутон; });
    var медиана = window.__ПИТЧ.медиана(полутоны);
    /* устойчивость: медианное абсолютное отклонение в полутонах */
    var отклонения = полутоны.map(function (п) { return Math.abs(п - медиана); });
    var мад = window.__ПИТЧ.медиана(отклонения);
    var устойчивость = Math.max(0, Math.min(1, 1 - мад / 0.8));

    /* старт: успел поймать тон в первой трети окна? */
    var первыйАктивный = активные[0].времяСек - окноНач;
    var длина = окноКон - окноНач;
    var старт = первыйАктивный <= длина * 0.4 ? 1 : (первыйАктивный <= длина * 0.7 ? 0.5 : 0.2);

    return {
      покрытие: покрытие,
      устойчивость: устойчивость,
      старт: старт,
      медианаПолутон: медиана,
      активных: активные.length
    };
  }

  /* ── Дружелюбный: щадящая вогнутая кривая ───────────────────────────────── */
  function другБалл(м) {
    if (!м || м.активных === 0) return null;
    var сырой = 0.45 * м.покрытие + 0.35 * м.устойчивость + 0.20 * м.старт;
    return 100 * Math.pow(сырой, 0.8); /* sqrt-семейство: слабым легче */
  }

  /* ── Судья: сырые числа + штраф девиации от эталона строки ──────────────── */
  function судБалл(м, эталонныйПолутон) {
    if (!м || м.активных === 0) return null;
    var сырой = 0.45 * м.покрытие + 0.35 * м.устойчивость + 0.20 * м.старт;
    var балл = 100 * сырой;
    if (эталонныйПолутон !== null && эталонныйПолутон !== undefined && isFinite(эталонныйПолутон)) {
      var девиация = Math.abs(м.медианаПолутон - эталонныйПолутон);
      балл -= Math.min(ПОРОГ.штрафМакс, девиация * ПОРОГ.штрафПолутон);
    }
    return Math.max(0, балл);
  }

  /* ── оценка всей попытки ───────────────────────────────────────────────────
     кадры, строки: [{индекс, меткаСек, конецСек}],
     эталон: { индексСтроки: полутон } — профиль лучшего дубля или null.      */
  function попытка(кадры, строки, эталон) {
    эталон = эталон || {};
    var построчно = [];
    var сумма = 0, штук = 0;
    var судСумма = 0, судШтук = 0;
    for (var i = 0; i < строки.length; i++) {
      var с = строки[i];
      var м = строкаМетрики(кадры, с, { порогЯсности: ПОРОГ.ясностьДруг });
      var друг = другБалл(м);
      /* судья меряет строгим порогом по своему набору кадров */
      var мСтрог = строкаМетрики(кадры, с, { порогЯсности: ПОРОГ.ясностьСуд });
      var эталонный = Object.prototype.hasOwnProperty.call(эталон, String(с.индекс)) ? эталон[String(с.индекс)] : null;
      var суд = судБалл(мСтрог, эталонный);
      построчно.push({
        индекс: с.индекс,
        покрытие: м.покрытие,
        устойчивость: м.устойчивость,
        старт: м.старт,
        медианаПолутон: м.медианаПолутон,
        друг: друг === null ? null : Math.round(друг * 10) / 10,
        суд: суд === null ? null : Math.round(суд * 10) / 10,
        девиацияПолутон: (эталонный !== null && м.медианаПолутон !== null)
          ? Math.round((м.медианаПолутон - эталонный) * 100) / 100 : null
      });
      if (друг !== null) { сумма += друг; штук++; }
      if (суд !== null) { судСумма += суд; судШтук++; }
    }
    return {
      построчно: построчно,
      итогДруг: штук ? Math.round(сумма / штук * 10) / 10 : null,
      итогСуд: судШтук ? Math.round(судСумма / судШтук * 10) / 10 : null
    };
  }

  /* ── Зелёный коридор: один шаг правил ─────────────────────────────────────
     кор: { копилка: bool, серия: number, отвоёвано: number },
     транспозиция: текущий сдвиг (цель — 0), друг/суд: баллы попытки.        */
  function коридорШаг(кор, транспозиция, друг, суд) {
    if (!кор || typeof кор !== 'object' || typeof кор.копилка !== 'boolean') {
      throw new TypeError('кор должен быть {копилка, серия, отвоёвано}');
    }
    var удача = (друг !== null && друг >= ПОРОГ.удачаДруг && суд !== null && суд >= ПОРОГ.удачаСуд);
    var следующий = { копилка: кор.копилка, серия: кор.серия || 0, отвоёвано: кор.отвоёвано || 0 };
    var результат = { удача: удача, событие: null, новаяТранспозиция: транспозиция, шагПолутон: 0 };

    if (!удача) {
      if (следующий.копилка || следующий.серия > 0) {
        следующий.копилка = false;
        следующий.серия = 0;
        результат.событие = 'Стрик коридора прерван — полшага сгорел';
      }
      return Object.assign(результат, { кор: следующий });
    }

    следующий.серия += 1;
    if (следующий.копилка) {
      /* вторая удачная подряд — полный полутон к оригиналу */
      следующий.копилка = false;
      следующий.серия = 0;
      if (транспозиция === 0) {
        результат.событие = 'Ты уже в оригинале — коридор празден, но серия засчитана';
      } else {
        var шаг = транспозиция > 0 ? -1 : 1;
        результат.новаяТранспозиция = транспозиция + шаг;
        результат.шагПолутон = 1;
        следующий.отвоёвано += 1;
        результат.событие = 'Зелёный коридор сузился: ' +
          (результат.новаяТранспозиция === 0 ? 'ты в оригинале!' : 'осталось ' + Math.abs(результат.новаяТранспозиция));
      }
    } else {
      следующий.копилка = true;
      результат.событие = 'Удача: полшага в копилку (удача ещё одна — и полутон вернётся)';
    }
    return Object.assign(результат, { кор: следующий });
  }

  /* ── профиль лучшего дубля: медианы строк {индексСтроки: полутон} ───────── */
  function профильИзПопытки(построчно) {
    if (!Array.isArray(построчно)) {
      throw new TypeError('построчно должен быть массивом строк попытки');
    }
    var профиль = {};
    for (var i = 0; i < построчно.length; i++) {
      var с = построчно[i];
      if (с.медианаПолутон !== null && isFinite(с.медианаПолутон)) {
        профиль[String(с.индекс)] = с.медианаПолутон;
      }
    }
    return профиль;
  }

  function инфо() {
    return {
      имя: ИМЯ,
      пороги: ПОРОГ,
      честность: '0 сети, 0 DOM, 0 случайности, 0 часов, вход не мутируется, отказы по-русски'
    };
  }

  window.__СЧЁТ = {
    имя: ИМЯ,
    пороги: ПОРОГ,
    строкаМетрики: строкаМетрики,
    другБалл: другБалл,
    судБалл: судБалл,
    попытка: попытка,
    коридорШаг: коридорШаг,
    профильИзПопытки: профильИзПопытки,
    инфо: инфо
  };
})();

EXTRA = {1: "Там, где другие гаснут, ты гори. До самого конца."}  # дописать финал

def wrap(t):
    return textwrap.fill(t, width=78, break_long_words=False, break_on_hyphens=False)

def process(n, pairs):
    hits = glob.glob(os.path.join(WORK, "%02d_*.txt" % n))
    if not hits:
        return [("ФАЙЛ НЕ НАЙДЕН", 0, False)]
    path = hits[0]
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    meta = lines[0] if lines and lines[0].startswith("META:") else None
    text = norm("\n".join(lines[1:] if meta else lines))
    report = []
    for old, new in pairs:
        o = norm(old)
        cnt = text.count(o)
        if cnt:
            text = text.replace(o, new)
            report.append(("OK×%d" % cnt, old[:48], True))
            continue
        m = re.findall(re.escape(o), text, flags=re.I)
        if m:
            text = re.sub(re.escape(o), lambda mm: new, text, flags=re.I)
            report.append(("OK(i)×%d" % len(m), old[:48], True))
        else:
            report.append(("MISS", old[:48], False))
    text = JUNK.sub("", text)
    text = re.sub(r"\s+", " ", text).strip()
    if n in EXTRA:
        text += " " + EXTRA[n]
    with open(path, "w", encoding="utf-8") as f:
        if meta:
            f.write(meta + "\n")
        f.write(wrap(text) + "\n")
    return report

def main():
    total_ok = total_miss = 0
    for n in sorted(CORR):
        print("== №%d ==" % n)
        for status, frag, ok in process(n, CORR[n]):
            mark = "  " if ok else "!!"
            print(" %s %-8s %s" % (mark, status, frag))
            total_ok += 1 if ok else 0
            total_miss += 0 if ok else 1
    print("\nИТОГО: применено %d, промахов %d" % (total_ok, total_miss))

if __name__ == "__main__":
    main()

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Piped-based YouTube pipeline: channel listing, search, subtitle extraction."""
import sys, re, json, time, gzip, urllib.request, urllib.parse

INSTANCES = [
    "https://api.piped.private.coffee",
    "https://pipedapi.adminforge.de",
    "https://pipedapi.kavin.rocks",
    "https://api.piped.yt",
    "https://pipedapi.drgns.space",
]
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"

def http(url, data=None, headers=None, timeout=25):
    h = {"User-Agent": UA, "Accept-Language": "ru-RU,ru;q=0.9"}
    if headers:
        h.update(headers)
    if data is not None:
        data = json.dumps(data).encode()
        h["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, headers=h)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        raw = r.read()
        if r.headers.get("Content-Encoding") == "gzip":
            raw = gzip.decompress(raw)
        return raw.decode("utf-8", "replace")

def api_get(path, retries=2):
    last = None
    for inst in INSTANCES:
        for _ in range(retries):
            try:
                raw = http(inst + path)
                return json.loads(raw), inst
            except Exception as e:
                last = e
                time.sleep(1)
    raise RuntimeError("all instances failed: %s (%s)" % (path, last))

MARKERS = re.compile(
    r"^[\[\(♪♫]*\s*(музыка|music|аплодисменты|applause|смех|смеётся|инструментал|instrumental)\s*[\]\)♪♫]*$",
    re.I)

def clean_json3(j3):
    words = []
    for ev in j3.get("events", []):
        segs = ev.get("segs")
        if not segs:
            continue
        t0 = ev.get("tStartMs", 0) / 1000.0
        txt = "".join(s.get("utf8", "") for s in segs).replace("\n", " ").strip()
        if not txt or MARKERS.match(txt) or txt.strip("♪♫ ") == "":
            continue
        words.append((t0, txt))
    return words

def parse_ttml(xml_text):
    """TTML -> list of (t0, text) per <p> element."""
    out = []
    for m in re.finditer(r"<p [^>]*>", xml_text):
        tag = m.group(0)
        start_pos = m.end()
        end = xml_text.find("</p>", start_pos)
        if end == -1:
            continue
        body = xml_text[start_pos:end]
        tm = re.search(r'begin="([\d.]+)', tag)
        t0 = float(tm.group(1)) if tm else 0.0
        txt = re.sub(r"<[^>]+>", " ", body)
        txt = re.sub(r"\s+", " ", txt).strip()
        txt = (txt.replace("&amp;", "&").replace("&quot;", '"')
                  .replace("&#39;", "'").replace("&lt;", "<").replace("&gt;", ">"))
        if not txt or MARKERS.match(txt) or txt.strip("♪♫ ") == "":
            continue
        out.append((t0, txt))
    return out

def lines_from_words(words, max_len=72, gap=1.0):
    lines, cur, last_t = [], [], None
    for t, w in words:
        if cur and ((last_t is not None and t - last_t > gap) or
                    (sum(len(x) for x in cur) + len(w) + 1 > max_len)):
            lines.append(" ".join(cur).strip())
            cur = []
        cur.append(w)
        last_t = t + 0.01
    if cur:
        lines.append(" ".join(cur).strip())
    merged = []
    for ln in lines:
        if merged and len(ln) < 16 and len(merged[-1]) + len(ln) < max_len + 14:
            merged[-1] += " " + ln
        else:
            merged.append(ln)
    return merged

def get_streams(video_id):
    return api_get("/streams/%s" % video_id)

def get_sub_lines(video_id):
    """Return (meta, lines, status)."""
    data, inst = get_streams(video_id)
    if "error" in data:
        return None, None, "error: %s" % data["error"]
    meta = {
        "title": data.get("title", ""),
        "uploader": data.get("uploader", ""),
        "duration": data.get("duration", 0),
    }
    subs = data.get("subtitles", []) or []
    ru = [s for s in subs if (s.get("code") or "").lower().startswith("ru")]
    pick = None
    for s in ru:
        if s.get("autoGenerated"):
            pick = s
    if pick is None and ru:
        pick = ru[0]
    if pick is None:
        return meta, None, "no-ru-subtitles"
    url = pick["url"]
    # prefer json3 over ttml
    if "fmt=ttml" in url:
        j3url = url.replace("fmt=ttml", "fmt=json3")
        try:
            raw = http(j3url)
            words = clean_json3(json.loads(raw))
            if words:
                return meta, lines_from_words(words), "ok-json3"
        except Exception:
            pass
    raw = http(url)
    if raw.lstrip().startswith("{"):
        words = clean_json3(json.loads(raw))
        lines = lines_from_words(words)
    else:
        segs = parse_ttml(raw)
        # TTML auto-captions: <p> chunks are phrase-level; group by gaps
        lines = lines_from_words(segs) if len(segs) > 0 else []
    if not lines:
        return meta, None, "empty-subtitles"
    return meta, lines, "ok"

def list_channel(channel_id, tag="videos"):
    """List all channel videos (paginated)."""
    items = []
    if tag == "videos":
        data, inst = api_get("/channel/%s" % channel_id)
        items.extend([s for s in data.get("relatedStreams", [])
                      if s.get("type") == "stream"])
        nextpage = data.get("nextpage")
        while nextpage:
            try:
                data2, _ = api_get("/nextpage/channel/%s?nextpage=%s"
                                   % (channel_id, urllib.parse.quote(nextpage)))
                batch = [s for s in data2.get("relatedStreams", [])
                         if s.get("type") == "stream"]
                if not batch:
                    break
                items.extend(batch)
                nxt = data2.get("nextpage")
                if nxt == nextpage:
                    break
                nextpage = nxt
                time.sleep(0.6)
            except Exception as e:
                print("nextpage stop: %s" % e, file=sys.stderr)
                break
    seen, out = set(), []
    for s in items:
        vid = s.get("url", "").split("v=")[-1]
        if vid in seen:
            continue
        seen.add(vid)
        out.append({"id": vid, "title": s.get("title", ""),
                    "dur": s.get("duration", 0)})
    return out

def search(query):
    q = urllib.parse.quote(query)
    data, inst = api_get("/search?q=%s&filter=videos" % q)
    out = []
    for s in data.get("items", []):
        if s.get("type") != "stream":
            continue
        out.append({"id": s.get("url", "").split("v=")[-1],
                    "title": s.get("title", ""),
                    "channel": s.get("uploaderName", ""),
                    "dur": s.get("duration", 0)})
    return out

def fmt_dur(sec):
    sec = int(sec or 0)
    return "%d:%02d" % (sec // 60, sec % 60)

if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "channel":
        for v in list_channel(sys.argv[2]):
            print("%s | %s | %s" % (v["id"], fmt_dur(v["dur"]), v["title"]))
    elif cmd == "search":
        for v in search(" ".join(sys.argv[2:])):
            print("%s | %s | %s | %s" % (v["id"], fmt_dur(v["dur"]), v["channel"], v["title"]))
    elif cmd == "subs":
        meta, lines, status = get_sub_lines(sys.argv[2])
        print("STATUS:", status)
        if meta:
            print("META:", json.dumps(meta, ensure_ascii=False))
        if lines:
            print("---")
            for ln in lines:
                print(ln)
